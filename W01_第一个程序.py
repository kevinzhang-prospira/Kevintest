# ---------- 1. 让屏幕说话 ----------
# print 是"打印"的意思：把括号里的内容显示到屏幕上
# 括号和引号都必须是英文的：( ) " "
print("你好，我是 Kevin")
print("这是我写的第一个程序")


# ---------- 2. 程序是一行一行往下执行的 ----------
print("第一行")
print("第二行")
print("第三行")


# ---------- 3. 引号里的内容可以随便改 ----------
print("我正在学 AI")
print("今天是 2026 年 9 月 16 日")


# ---------- 4. 源码里的空行，不会跑到屏幕上 ----------
# 上面我空了好几行，但你看输出：屏幕上并没有多出空行。
# 空行和 # 注释一样，只是写给人看的，电脑会跳过。
print("我上面空了好几行，但屏幕上并不会多出空行")


