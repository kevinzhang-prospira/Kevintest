# ==========================================
# 第 4 部分：布尔 bool —— 只有两个值
# ==========================================
print()
print("===== 第 4 部分：布尔 =====")

# 必须首字母大写！true / TRUE 都会报错
is_ok = True
is_full = False
print(is_ok, is_full)

# 比较运算的结果，全是布尔
print(3 > 2)      # True
print(3 < 2)      # False
print(3 >= 3)     # True
print(3 == 3)     # True
print(3 != 3)     # False

# ⚠️ 大坑：= 是"装进去"，== 是"问一句"
age = 40              # 一个等号：赋值（把 40 装进 age）
print(age == 40)      # 两个等号：比较 → True
print(age == 41)      # → False

# 冷知识：True 当数字用时是 1
print(True + True)    # 2


# ==========================================
# 第 5 部分：类型转换四兄弟
# ==========================================
print()
print("===== 第 5 部分：转换 =====")

print(int("40"))       # 40      文字 → 整数
print(float("3.14"))   # 3.14    文字 → 小数
print(str(40))         # 40      数字 → 文字
print(bool(1))         # True
print(bool(0))         # False

# 坑一：int() 是"砍掉小数"，不是四舍五入
print(int(3.99))       # 3
print(round(3.99))     # 4       round() 才是四舍五入

# 坑二：int("3.14") 会报 ValueError（值不对），得先 float 再 int
print(int(float("3.14")))    # 3
# print(int("3.14"))         # ← 取消注释会报 ValueError: invalid literal for int()


