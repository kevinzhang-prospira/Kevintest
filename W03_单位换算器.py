# ==========================================
# 第 1 部分：type() —— 问它"你是什么"
# ==========================================
print("===== 第 1 部分：先看看它们都是什么 =====")

# type() 的用法跟 print() 一样：把东西递进去，它告诉你类型
print(type("你好"))      # str    = 字符串（文字）
print(type(40))          # int    = 整数
print(type(3.14))        # float  = 小数（浮点数）
print(type(True))        # bool   = 布尔（真/假）

# <class 'xxx'> 里的 xxx 就是类型名，外面这层包装先无视


# ==========================================
# 第 2 部分：数字 —— int 和 float
# ==========================================
print()
print("===== 第 2 部分：两种数字 =====")

# 有没有小数点，决定它是 int 还是 float
print(type(7))       # int
print(type(7.0))     # float  ← 哪怕看着像整数，有小数点就是 float

# 七个运算符
print(7 + 3)     # 10                        加
print(7 - 3)     # 4                         减
print(7 * 3)     # 21                        乘
print(7 / 3)     # 2.3333333333333335        除
print(7 // 3)    # 2                         整除：只要整数部分
print(7 % 3)     # 1                         取余：只要零头
print(7 ** 3)    # 343                       幂：7 的 3 次方

# 用处举例：20 个零件，每箱装 6 个
print(f"20 个零件能装满 {20 // 6} 箱，还剩 {20 % 6} 个")

# 必须记住的第 ① 条：/ 的结果永远是 float，哪怕除得尽
print(10 / 2)    # 5.0   ← 不是 5，是 5.0

# 必须记住的第 ② 条：float 不是"精确"的（这不是 Bug）
print(0.1 + 0.2)     # 0.30000000000000004


