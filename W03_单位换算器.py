# 三个高频小工具：len / strip / upper
name = "  Kevin Zhang  "
print(len(name))              # 15           连两头的空格一起数
print(name.strip())           # 去掉两头的空格
print(name.upper())           # 全大写
print(name.lower())           # 全小写
print(len(name.strip()))      # 11           先清空格再数，就对了

