# ==========================================
# 第 1 部分：变量 = 贴了标签的盒子
# （这部分不用你输入，跑完直接出结果）
# ==========================================
print("===== 第 1 部分：变量 =====")

# = 读作"把右边的装进左边的盒子"，不是数学里的"相等"
#     标签      盒子里的东西
#      ↓            ↓
name = "Kevin"
print(name)          # 不加引号 → 打开盒子，打里面的东西

city = "宁国"
print(city)

# 盒子里的东西可以换：同一个盒子，先后装不同的东西
number = 1
print(number)
number = 2
print(number)        # 只看最后装进去的，1 已经被覆盖


# ==========================================
# 第 2 部分：加引号 和 不加引号，是两回事
# ==========================================
print()
print("===== 第 2 部分：引号的分界线 =====")

animal = "猫"

print("animal")      # 加引号 → 打出来的是 animal 这六个字母
print(animal)        # 不加引号 → 打开盒子，打出来的是 猫

# 数字不用加引号，而且能算数
age = 40
print(age)
print(age + 1)       # 41


# ==========================================
# 第 3 部分：input() —— 让程序开口问你
# ⚠️ 从这里开始，程序会停下来等你打字。它没死机，是在等你。
# ==========================================
print()
print("===== 第 3 部分：让程序问你 =====")

# input 干了两件事：
#   1. 把括号里的提示语显示在屏幕上，然后停下等你
#   2. 你打完按回车 → 你打的内容被装进左边这个盒子
your_name = input("你叫什么名字？ ")

print(your_name)     # 看看盒子里装了什么


# ==========================================
# 第 4 部分：把答案编进回复里（两种写法）
# ==========================================
print()
print("===== 第 4 部分：接话的两种方式 =====")

# 写法一：用 + 把文字接起来（+ 的两边必须都是文字）
print("你好，" + your_name)

# 写法二（推荐）：f-string
#   在引号前面加一个小写字母 f，然后就能在 { } 里直接塞变量
print(f"你好，{your_name}，很高兴认识你！")


# ==========================================
# 第 5 部分：今天最大的坑 —— input 收回来的永远是"文字"
# ==========================================
print()
print("===== 第 5 部分：小心这个坑 =====")

# 哪怕你敲的是纯数字，input 收回来的也是"文字形态的数字"
age_text = input("你今年多大？ ")

print(f"你输入的是：{age_text}")
print(f"它的类型是：{type(age_text)}")     # str = 文字（string 的缩写）

# ↓ 下面这行是故意留的"反面教材"，先别急着取消注释。等你做完作业再试。
print(age_text + 1)      # ← 会报 TypeError：文字不能跟数字相加

# 解法：用 int() 把"文字"翻译成"整数"
age = int(age_text)
print(f"翻译成数字后是：{age}，类型变成 {type(age)}")
print(f"年龄加 1 等于：{age + 1}")
print(f"顺便看看你是哪年生的：{2026 - age}")


